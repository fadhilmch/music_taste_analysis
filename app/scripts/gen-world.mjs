import { geoCentroid, geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import world110 from 'world-atlas/countries-110m.json' with { type: 'json' };
import iso from 'i18n-iso-countries';
import enLocale from 'i18n-iso-countries/langs/en.json' with { type: 'json' };
import { writeFileSync } from 'node:fs';

iso.registerLocale(enLocale);
const W = 960,
  H = 500;
const fc = feature(world110, world110.objects.countries);
const projection = geoNaturalEarth1().fitSize([W, H], { type: 'Sphere' });
const path = geoPath(projection);
const shapes = [];
const alpha2ByNumeric = {};
for (const f of fc.features) {
  const id = String(f.id ?? '');
  if (!id || id === '099') continue;
  const c = projection(geoCentroid(f));
  const d = path(f);
  if (!c || !d) continue;
  const alpha2 = iso.numericToAlpha2(id);
  shapes.push({
    id,
    alpha2: alpha2 ?? null,
    name: f.properties?.name ?? 'Unknown',
    cx: +c[0].toFixed(1),
    cy: +c[1].toFixed(1),
    d,
  });
  if (alpha2)
    alpha2ByNumeric[alpha2] = { id, name: iso.getName(alpha2, 'en') ?? f.properties?.name ?? alpha2 };
}
const sphere = path({ type: 'Sphere' });
const out = `/* Generated by scripts/gen-world.mjs from Natural Earth 110m (public domain)
   and i18n-iso-countries (MIT). Do not edit by hand. Projection: d3
   geoNaturalEarth1 fitted to ${W}x${H}; paths and centroids are precomputed so
   the app renders the world fully offline with zero geo dependencies. */

export const WORLD_W = ${W};
export const WORLD_H = ${H};
export const WORLD_SPHERE = ${JSON.stringify(sphere)};

export interface WorldCountry { id: string; alpha2: string | null; name: string; cx: number; cy: number; d: string }

export const WORLD_COUNTRIES: WorldCountry[] = ${JSON.stringify(shapes)};

/** alpha2 -> { numeric id, English display name } for countries on the map. */
export const COUNTRY_INFO: Record<string, { id: string; name: string }> = ${JSON.stringify(alpha2ByNumeric)};
`;
writeFileSync('src/data/worldData.ts', out);
console.log(
  'countries:',
  shapes.length,
  'alpha2:',
  Object.keys(alpha2ByNumeric).length,
  'bytes:',
  out.length,
);
